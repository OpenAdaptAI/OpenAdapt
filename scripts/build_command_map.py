"""Render CAPABILITIES.md's "Every command, by capability" list from files.

Each openadapt-flow command has one file, packages/flow/docs/commands/<group>/<verb>.md.
The group directory names the capability (its README.md holds the title; the
numeric prefix sets the order). A command's file is empty or holds a one-line
note shown after it. Adding a command adds a file, and the rendered list has
one command per line, so two pull requests that add commands rarely touch the
same line.

    python scripts/build_command_map.py          # rewrite the section
    python scripts/build_command_map.py --check  # fail if it is out of date

packages/flow/tests/test_capabilities_map.py fails when a command has no file,
a file names no command, or the section is out of date.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "CAPABILITIES.md"
COMMANDS = ROOT / "packages/flow/docs/commands"
HEADING = "## Every command, by capability"
BEGIN = "<!-- BEGIN generated by scripts/build_command_map.py -->"
END = "<!-- END generated by scripts/build_command_map.py -->"


def groups(root: Path = COMMANDS) -> list[tuple[str, dict[str, str]]]:
    """Return (title, {verb: note}) per capability, in directory order."""
    result: list[tuple[str, dict[str, str]]] = []
    for directory in sorted(path for path in root.iterdir() if path.is_dir()):
        title = (directory / "README.md").read_text("utf-8").strip()
        if not title.startswith("# "):
            raise SystemExit(f"{directory}/README.md must be a single '# Title' line")
        verbs = {
            path.stem: path.read_text("utf-8").strip()
            for path in sorted(directory.glob("*.md"))
            if path.name != "README.md"
        }
        result.append((title[2:], verbs))
    return result


def documented_verbs(root: Path = COMMANDS) -> list[str]:
    return sorted(verb for _, verbs in groups(root) for verb in verbs)


def render(root: Path = COMMANDS) -> str:
    lines = [BEGIN, ""]
    for title, verbs in groups(root):
        lines += [f"**{title}:**", ""]
        for verb, note in verbs.items():
            lines.append(f"- `{verb}`" + (f": {note}" if note else ""))
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def splice(text: str, block: str) -> str:
    start, end = text.index(BEGIN), text.index(END) + len(END)
    if text.rfind(HEADING, 0, start) == -1:
        raise SystemExit(f"the generated block must sit under '{HEADING}'")
    return text[:start] + block + text[end:]


def main(argv: list[str]) -> int:
    text = MAP.read_text("utf-8")
    updated = splice(text, render())
    if "--check" in argv:
        if updated != text:
            print(
                "CAPABILITIES.md command list is out of date; "
                "run: python scripts/build_command_map.py"
            )
            return 1
        return 0
    MAP.write_text(updated, "utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
