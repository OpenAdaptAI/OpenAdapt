#!/usr/bin/env node
// A pinned, checksummed copy of @openadapt/program-graph for a repository
// that cannot install it from npm yet (openadapt-web, openadapt-cloud).
//
//   node packages/program-graph/scripts/vendor.mjs --out ../openadapt-web/vendor/program-graph
//       Build at the current commit and write the copy, its VENDOR.json
//       manifest (commit, version, sha256 of every file) and check.mjs.
//   node <copy>/check.mjs
//       In the consuming repository's CI: fail when any vendored file was
//       edited, added or removed. Needs only Node.
//   node packages/program-graph/scripts/vendor.mjs --verify <copy>
//       In an OpenAdapt checkout at the copy's commit: rebuild and confirm the
//       copy is exactly what that commit builds.
//
// The build refuses uncommitted changes under packages/program-graph, so the
// commit in VENDOR.json always names the source of the files.
import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const allowDirty = args.includes("--allow-dirty");

const COPIED = [
  ["dist", "."],
  ["schema", "schema"],
  ["fixtures/openemr-referral/spec.json", "fixtures/openemr-referral/spec.json"],
  ["fixtures/openemr-referral/folds.json", "fixtures/openemr-referral/folds.json"],
  ["fixtures/openemr-referral/trace.json", "fixtures/openemr-referral/trace.json"],
  ["LICENSE", "LICENSE"],
  ["README.md", "README.md"],
];

const CHECK = `#!/usr/bin/env node
// Verify this vendored copy of @openadapt/program-graph against VENDOR.json.
// Generated by OpenAdapt packages/program-graph/scripts/vendor.mjs. Do not edit.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const dir = path.dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(dir, "VENDOR.json"), "utf8"));
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(path.join(d, e.name)) : [path.relative(dir, path.join(d, e.name)).split(path.sep).join("/")]);
const present = new Set(walk(dir).filter((f) => f !== "VENDOR.json" && f !== "check.mjs"));
const problems = [];
for (const [file, sha] of Object.entries(manifest.files)) {
  if (!present.delete(file)) { problems.push(\`missing \${file}\`); continue; }
  const got = crypto.createHash("sha256").update(fs.readFileSync(path.join(dir, file))).digest("hex");
  if (got !== sha) problems.push(\`changed \${file}\`);
}
for (const file of present) problems.push(\`not in VENDOR.json: \${file}\`);
const lines = Object.entries(manifest.files).sort(([a], [b]) => (a < b ? -1 : 1)).map(([f, s]) => \`\${s}  \${f}\\n\`).join("");
if (crypto.createHash("sha256").update(lines).digest("hex") !== manifest.digest) problems.push("digest does not match the file list");
if (problems.length) {
  console.error(\`@openadapt/program-graph vendored copy differs from VENDOR.json:\\n  \${problems.join("\\n  ")}\`);
  process.exit(1);
}
console.log(\`@openadapt/program-graph \${manifest.version} at \${manifest.source.commit.slice(0, 12)}: \${Object.keys(manifest.files).length} files verified\`);
`;

const sha256 = (file) => crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)],
  );
const git = (...a) => execFileSync("git", a, { cwd: root, encoding: "utf8" }).trim();

function build(out) {
  const dirty = git("status", "--porcelain", "--", ".");
  if (dirty && !allowDirty) {
    console.error(`packages/program-graph has uncommitted changes; commit them first (or pass --allow-dirty for a local trial):\n${dirty}`);
    process.exit(2);
  }
  execFileSync(process.execPath, [path.join(root, "scripts", "build.mjs")], { stdio: "inherit" });
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  for (const [from, to] of COPIED) fs.cpSync(path.join(root, from), path.join(out, to), { recursive: true });
  const files = {};
  for (const file of walk(out).sort()) files[path.relative(out, file).split(path.sep).join("/")] = sha256(file);
  const lines = Object.entries(files)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([file, sha]) => `${sha}  ${file}\n`)
    .join("");
  const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
  const manifest = {
    package: pkg.name,
    version: pkg.version,
    license: pkg.license,
    source: {
      repository: "https://github.com/OpenAdaptAI/OpenAdapt",
      path: "packages/program-graph",
      commit: git("rev-parse", "HEAD"),
      dirty: Boolean(dirty),
    },
    peer_dependencies: pkg.peerDependencies,
    files,
    digest: crypto.createHash("sha256").update(lines).digest("hex"),
  };
  fs.writeFileSync(path.join(out, "VENDOR.json"), JSON.stringify(manifest, null, 2) + "\n");
  fs.writeFileSync(path.join(out, "check.mjs"), CHECK);
  return manifest;
}

const verify = flag("--verify");
const out = flag("--out");
if (verify) {
  const theirs = JSON.parse(fs.readFileSync(path.join(verify, "VENDOR.json"), "utf8"));
  execFileSync(process.execPath, [path.join(verify, "check.mjs")], { stdio: "inherit" });
  if (theirs.source.commit !== git("rev-parse", "HEAD")) {
    console.error(`the copy was built at ${theirs.source.commit}; check out that commit first`);
    process.exit(1);
  }
  const ours = build(fs.mkdtempSync(path.join(os.tmpdir(), "program-graph-")));
  if (ours.digest !== theirs.digest) {
    console.error(`rebuilt digest ${ours.digest} differs from the copy's ${theirs.digest}`);
    process.exit(1);
  }
  console.log(`the copy is exactly what ${ours.source.commit.slice(0, 12)} builds (digest ${ours.digest})`);
} else if (out) {
  const manifest = build(path.resolve(out));
  console.log(`wrote ${path.relative(process.cwd(), path.resolve(out))}: ${manifest.package} ${manifest.version} at ${manifest.source.commit.slice(0, 12)}, digest ${manifest.digest}`);
} else {
  console.error("usage: vendor.mjs --out <dir> | --verify <dir> [--allow-dirty]");
  process.exit(2);
}
