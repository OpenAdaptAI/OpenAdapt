// Pin-bound exports and generated phone files must survive Git's checkout
// conversions. Exercise the real filters, not the spelling of .gitattributes.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { expect, it } from "vitest";

const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repository = path.resolve(desktop, "../..");
const shell = "packages/desktop/openadapt_desktop/portal/shell/";
const selected = spawnSync("git", [
  "ls-files", "-z", "--", "packages/desktop/src/styles/vendor/",
  `${shell}styles.css`, `${shell}index.html`, `${shell}manifest.webmanifest`, `${shell}fonts/`,
], { cwd: repository, encoding: "utf8" });
expect(selected.status, selected.stderr).toBe(0);
const files = selected.stdout.split("\0").filter(Boolean);
expect(files).toContain("packages/desktop/src/styles/vendor/openadapt-web/tokens.css");
expect(files).toContain("packages/desktop/src/styles/vendor/semantic-theme/semantic-theme.css");
expect(files).toContain(`${shell}styles.css`);

it.each([false, true])("preserves every pinned/generated byte with core.autocrlf=%s", (autocrlf) => {
  const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "openadapt-theme-checkout-"));
  try {
    const destination = path.join(temporary, "checkout");
    const prefix = destination.split(path.sep).join("/") + "/";
    const checked = spawnSync("git", [
      "-c", `core.autocrlf=${autocrlf}`, "checkout-index", `--prefix=${prefix}`, "-z", "--stdin",
    ], { cwd: repository, input: files.join("\0") + "\0", encoding: "utf8" });
    expect(checked.status, checked.stderr).toBe(0);
    for (const file of files) {
      expect(fs.readFileSync(path.join(destination, file)), file)
        .toEqual(fs.readFileSync(path.join(repository, file)));
    }
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
});
