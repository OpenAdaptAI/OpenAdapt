def __getattr__(name: str) -> Any:
    submodule = _EXPORTS.get(name)
    if submodule is not None:
        value = getattr(importlib.import_module(f"{__name__}.{submodule}"), name)
        globals()[name] = value
        return value
    if name == "__version__":
        from importlib import metadata

        try:
            version = metadata.version("openadapt-types")
        except metadata.PackageNotFoundError:  # pragma: no cover - source checkout only
            # Never report a hard-coded version. An unmeasurable version is
            # reported as unknown so a caller cannot mistake a stale literal
            # for the installed one.
            version = "unknown"
        globals()["__version__"] = version
        return version
    if not name.startswith("_") and importlib.util.find_spec(f"{__name__}.{name}") is not None:
        # ``openadapt_types.seal`` and friends worked as attributes when the
        # root imported every submodule; keep that, still lazily.
        return importlib.import_module(f"{__name__}.{name}")
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def __dir__() -> list[str]:
    return sorted(set(globals()) | set(__all__) | {"__version__"})


