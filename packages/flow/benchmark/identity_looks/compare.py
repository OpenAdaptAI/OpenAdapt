#!/usr/bin/env python3
"""Write IDENTITY_LOOKS.md from a before and an after dense-list run.

Usage::

    python benchmark/identity_looks/compare.py results_before.json results_after.json \\
        > benchmark/identity_looks/IDENTITY_LOOKS.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROWS = (
    ("recorded", "shipped", "Recorded record, no list, no copy"),
    ("recorded", "list", "Recorded record, known-ID list"),
    ("recorded", "copy", "Recorded record, copy look"),
    ("recorded", "list_copy", "Recorded record, list and copy look"),
    ("param", "shipped", "Run parameter, no list, no copy"),
    ("param", "list", "Run parameter, known-ID list"),
    ("param", "copy", "Run parameter, copy look"),
    ("param", "list_copy", "Run parameter, list and copy look"),
)


def _pct(n: int, d: int) -> str:
    return f"{100.0 * n / d:.1f}%" if d else "n/a"


def _cell(b: dict[str, Any] | None, key: str, den: str) -> str:
    if b is None:
        return "not in this version"
    return f"{b[key]} / {b[den]} ({_pct(b[key], b[den])})"


def table(before: dict[str, Any], after: dict[str, Any], scope: str) -> list[str]:
    lines = [
        "| Mode and looks | False stops, before | False stops, after "
        "| Wrong-record accepts, before | Wrong-record accepts, after |",
        "| --- | --- | --- | --- | --- |",
    ]
    for mode, variant, label in ROWS:
        key = f"{mode}/{variant}"
        b = before["scored"].get(key, {}).get(scope)
        a = after["scored"].get(key, {}).get(scope)
        if a is None:
            continue
        lines.append(
            f"| {label} | {_cell(b, 'false_stops', 'correct_row_clicks')} "
            f"| {_cell(a, 'false_stops', 'correct_row_clicks')} "
            f"| {_cell(b, 'wrong_record_accepts', 'sibling_row_clicks')} "
            f"| {_cell(a, 'wrong_record_accepts', 'sibling_row_clicks')} |"
        )
    return lines


def by_class(after: dict[str, Any]) -> list[str]:
    classes = sorted(k for k in after["scored"]["param/shipped"] if k != "all")
    lines = [
        "| Collision class | No list, no copy | Known-ID list | Copy look "
        "| List and copy | Wrong-record accepts (any) |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for cls in classes:
        cells = []
        wrong = 0
        for variant in ("shipped", "list", "copy", "list_copy"):
            b = after["scored"][f"param/{variant}"][cls]
            cells.append(f"{b['false_stops']} / {b['correct_row_clicks']}")
            wrong += b["wrong_record_accepts"]
        lines.append(f"| `{cls}` | " + " | ".join(cells) + f" | {wrong} |")
    return lines


def main() -> int:
    before = json.loads(Path(sys.argv[1]).read_text())
    after = json.loads(Path(sys.argv[2]).read_text())
    meta = after["meta"]
    a = after["scored"]
    stops = {k: a[k]["all"] for k in a}
    n = stops["param/shipped"]["correct_row_clicks"]
    out = [
        "# Extra identity looks on the dense record list: before and after",
        "",
        "Generated by `benchmark/identity_looks/compare.py` from "
        "`results_before.json` (commit "
        f"`{before['meta']['commit'][:9]}`, origin/main) and `results_after.json` "
        f"(commit `{meta['commit'][:9]}`). Synthetic data only.",
        "",
        "## What was measured",
        "",
        "- The real `Replayer._verify_identity` against the dense record list of "
        f"`benchmark/dense_surface` ({meta['n_rows']} rows, seeds "
        f"{', '.join(str(s) for s in meta['seeds'])}), rendered live in "
        "Chromium and read by RapidOCR "
        "(`python -m openadapt_flow.validation.identity_looks_dense`).",
        "- The pixel path the compiler builds for a pixel recording: the "
        "identifier region is the tight box around the row's identity text, and "
        "the recorded identity is the OCR text inside it.",
        f"- Replay conditions: {', '.join(meta['replay_conditions'])}; each "
        "recorded at the same device scale as its replay. Click configs: "
        f"{', '.join(meta['click_configs'])}.",
        "- A false stop is a click on the correct row that the check does not "
        "verify, at the step-entry check or at the check just before the click. "
        "A wrong-record accept is a click on the adjacent sibling row that "
        "verifies at either check. Both counts use the same "
        f"{n} armed clicks.",
        "- **Recorded record**: the band names the record the demonstration "
        "opened. **Run parameter**: the record's ID is a run parameter, as in a "
        "worklist, and the band embeds it.",
        "- **Known-ID list**: every ID in the seed's table, as a complete list. "
        "**Copy look**: a real mouse drag across the identifier's text box in "
        "the live page; the copied text is the page's selection, which is what "
        "a redirected remote clipboard receives.",
        "- The before run is origin/main, where the copy look does not exist. "
        "Its list column is the earlier design (one fresh capture).",
        "",
        "## Headline",
        "",
        f"- No list, no copy: **{stops['param/shipped']['false_stops']} / {n}** "
        "correct-row clicks stop (no change; the extra looks need a list or a "
        "copy to settle anything).",
        f"- Known-ID list: **{before['scored']['param/list']['all']['false_stops']}"
        f" / {n}** before, **{stops['param/list']['false_stops']} / {n}** after.",
        f"- Copy look with the ID as a run parameter: "
        f"**{stops['param/copy']['false_stops']} / {n}**; with the list too: "
        f"**{stops['param/list_copy']['false_stops']} / {n}**.",
        "- Copy look in recorded-record mode: "
        f"**{stops['recorded/copy']['false_stops']} / {n}** (it can stop a run "
        "but never confirm one there).",
        "- Wrong-record accepts: **"
        + str(sum(v["wrong_record_accepts"] for v in stops.values()))
        + f"** across all {len(stops)} after configurations, and **"
        + str(sum(v["all"]["wrong_record_accepts"] for v in before["scored"].values()))
        + "** before.",
        "",
        "## All clicks",
        "",
        *table(before, after, "all"),
        "",
        "## By collision class (run parameter, after)",
        "",
        "In the `id_*` classes the sibling's ID differs from the target's only "
        "by a look-alike glyph. OCR and the list cannot tell them apart; the "
        "copy can.",
        "",
        *by_class(after),
        "",
        "## What is left",
        "",
        "Of the stops left with the copy look and a run parameter, almost all "
        "are in `id_confusion_O0` (IDs like `C0X1234`). There the recording "
        "itself read the ID with a letter O, so the recorded band does not "
        "contain the parameter's value and is not linked to it; with no exact "
        "value to compare, the copy can only agree, not confirm. The rest are "
        "dense-row reads that drop or garble a cell, a mismatch that no look "
        "may overrule. Per-trial looks are in `results_after.json`.",
        "",
        "Without a run parameter (a workflow that always opens the recorded "
        "record), the copy confirms nothing: the recorded ID is OCR text and "
        "may itself be a misread. There, only the known-ID list helps.",
        "",
        "## Limits",
        "",
        "- One fixture, one OCR engine (RapidOCR), synthetic rows, a browser "
        "page. A real RDP or Citrix session adds compression and its own "
        "clipboard policy; many deployments turn clipboard redirection off, "
        "and then the copy look is unavailable.",
        "- The fixture renders deterministically, so fresh frames repeat the "
        "first. These numbers show what the looks cost and settle, not what the "
        "fresh frames guard against (a caret or a repaint between captures).",
        "- Selecting text in this table changes nothing. In an application where "
        "a drag on the identifier triggers something, the look stops the run if "
        "the screen changes outside the identifier, but the deployment must "
        "only turn the copy look on where selection is inert.",
        "",
    ]
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
