"""Build the OpenEMR compose project from OpenEMR's pinned production compose.

OpenEMR is GPL-3.0, so its production compose file is not stored in this
repository. ``prepare_compose`` fetches ``docker/production/docker-compose.yml``
from ``openemr/openemr`` at the commit pinned in ``environment.lock.json``,
checks its SHA-256, caches it under ``out/upstream`` (git-ignored), and derives
the local compose file from it:

* the ``mysql`` service is named ``db``; both services keep upstream's
  command, healthcheck and mounts;
* images come from required, digest-pinned variables, never upstream tags;
* the literal demo credentials are replaced by required generated secrets;
* ports bind to loopback only, and ``restart: always`` is dropped so a
  benchmark stack never restarts itself after the run.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

import yaml

from .pinned_fetch import UpstreamFetchError, cache_root, fetch_pinned

HERE = Path(__file__).resolve().parent
UPSTREAM_KEY = "openemr"
REPO = "openemr/openemr"
COMPOSE = "docker/production/docker-compose.yml"
SECRET = "generated fixture secret required"

__all__ = ["UpstreamFetchError", "prepare_compose", "render_compose"]


def _req(var: str, what: str) -> str:
    return "${" + var + ":?" + what + "}"


ROOT_PASSWORD = _req("MARIADB_ROOT_PASSWORD", SECRET)
DB_ENV = {
    "MARIADB_ROOT_PASSWORD": ROOT_PASSWORD,
    "MYSQL_ROOT_PASSWORD": ROOT_PASSWORD,
}
OPENEMR_ENV = {
    "MYSQL_HOST": "db",
    "MYSQL_ROOT_PASS": ROOT_PASSWORD,
    "MYSQL_USER": "openemr",
    "MYSQL_PASS": _req("OPENEMR_DB_PASSWORD", SECRET),
    "MYSQL_DATABASE": "openemr",
    "OE_USER": _req("OPENEMR_ACTOR_USER", "fixture actor required"),
    "OE_PASS": _req("OPENEMR_ACTOR_PASSWORD", SECRET),
}
PORTS = [
    "127.0.0.1:${OPENEMR_HTTP_PORT:-9301}:80",
    "127.0.0.1:${OPENEMR_HTTPS_PORT:-9300}:443",
]
VOLUME_NAMES = {
    "databasevolume": "database",
    "logvolume01": "logs",
    "sitevolume": "sites",
}


def _rename_volumes(volumes: Any) -> list[str]:
    out = []
    for item in volumes or []:
        name, _, target = str(item).partition(":")
        if name not in VOLUME_NAMES:
            raise UpstreamFetchError(f"unexpected upstream volume {item!r}")
        out.append(f"{VOLUME_NAMES[name]}:{target}")
    return out


def render_compose(upstream_compose: Path) -> dict[str, Any]:
    doc = yaml.safe_load(upstream_compose.read_text())
    services = doc.get("services", {})
    if set(services) != {"mysql", "openemr"}:
        raise UpstreamFetchError(f"upstream services changed: {sorted(services)}")
    for name, expected in (
        ("mysql", {"MYSQL_ROOT_PASSWORD"}),
        ("openemr", set(OPENEMR_ENV) - {"MYSQL_DATABASE"}),
    ):
        names = set(services[name].get("environment", {}))
        if not expected <= names | {"MYSQL_DATABASE"}:
            raise UpstreamFetchError(
                f"upstream {name} environment changed: {sorted(names)}"
            )

    db = dict(services["mysql"])
    db.pop("restart", None)
    db["image"] = _req("MARIADB_IMAGE", "pinned MARIADB_IMAGE required")
    db["environment"] = dict(DB_ENV)
    db["volumes"] = _rename_volumes(db.get("volumes"))

    emr = dict(services["openemr"])
    emr.pop("restart", None)
    emr["image"] = _req("OPENEMR_IMAGE", "pinned OPENEMR_IMAGE required")
    emr["depends_on"] = {"db": emr["depends_on"]["mysql"]}
    emr["environment"] = dict(OPENEMR_ENV)
    emr["ports"] = list(PORTS)
    emr["volumes"] = _rename_volumes(emr.get("volumes"))

    order = [
        "image",
        "command",
        "depends_on",
        "environment",
        "healthcheck",
        "ports",
        "volumes",
    ]

    def ordered(svc: dict[str, Any]) -> dict[str, Any]:
        return {k: svc[k] for k in order if k in svc} | {
            k: v for k, v in svc.items() if k not in order
        }

    return {
        "services": {"db": ordered(db), "openemr": ordered(emr)},
        "volumes": {"database": None, "logs": None, "sites": None},
    }


def prepare_compose(
    lock: Mapping[str, Any], *, out_dir: Path | None = None, opener=None
) -> Path:
    upstream = lock["upstreams"][UPSTREAM_KEY]
    commit = upstream["commit"]
    files = {COMPOSE: upstream["files"][COMPOSE]}
    base = cache_root((out_dir or HERE / "out") / "upstream")
    kwargs = {"opener": opener} if opener is not None else {}
    root = fetch_pinned(REPO, commit, files, base, **kwargs)
    target = root.parent / f"compose.{commit[:12]}.yml"
    header = (
        f"# Generated by benchmark/openemr_local/upstream.py from openemr/openemr {commit}\n"
        f"# {COMPOSE} (GPL-3.0). Local use only; do not commit.\n"
    )
    target.write_text(
        header + yaml.safe_dump(render_compose(root / COMPOSE), sort_keys=False)
    )
    return target


if __name__ == "__main__":  # pragma: no cover - manual helper
    print(prepare_compose(json.loads((HERE / "environment.lock.json").read_text())))
