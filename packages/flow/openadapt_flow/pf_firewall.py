"""macOS ``pf`` rules that hold the service account to the no-outbound allow list.

Strict no-outbound mode refuses connections inside the Flow Python process,
and the egress audit samples the socket table of the whole process tree. A
non-Python child (the remote-desktop client, a helper tool) can still open a
connection between two samples. In strict mode the installer therefore adds a
``pf`` anchor that blocks every outbound TCP and UDP packet from sockets owned
by the service account, except to loopback and to the allow-list entries.
The kernel enforces it for every process the account runs. Connection
sampling stays on as the audit record.

This module only renders and checks text. It never runs ``pfctl``. The
installer (``deploy/on-prem/bin/install-macos.sh``) writes the anchor with
administrator rights, asks ``pfctl -nf`` to parse it, and loads it.

``pf`` matches ``user`` only for TCP and UDP sockets. Other protocols (ICMP,
for example) are not covered by these rules; the site firewall stays the
primary control for those.
"""

from __future__ import annotations

import ipaddress
import re
from dataclasses import dataclass
from typing import Iterable, Optional, Sequence

from openadapt_flow.no_outbound_allow import AllowEntry

ANCHOR = "ai.openadapt.flow"
ANCHOR_PATH = f"/etc/pf.anchors/{ANCHOR}"
PF_CONF = "/etc/pf.conf"
HEADER = f"# {ANCHOR}: generated by openadapt-flow. Edit the allow list, not this file."

_USER_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_.-]{0,63}$")
_ADDR = r"[0-9A-Fa-f:.]+(?:/\d{1,3})?"
_RULE_RES = (
    re.compile(r"^pass out quick on lo0 all$"),
    re.compile(
        r"^pass out quick proto (tcp|udp|\{ tcp udp \}) from any to "
        rf"(?P<addr>{_ADDR})( port (?P<port>\d{{1,5}}))? user (?P<user>\S+) keep state$"
    ),
    re.compile(
        r"^block return out log quick proto \{ tcp udp \} from any to any "
        r"user (?P<user>\S+)$"
    ),
)


class PfRuleError(ValueError):
    """The rules cannot be rendered, or a rendered anchor fails the check."""


@dataclass(frozen=True)
class PfPlan:
    """What the installer writes. Text only; nothing is applied here."""

    anchor_text: str
    pf_conf_lines: tuple[str, str]
    anchor_path: str = ANCHOR_PATH


def _check_user(user: str) -> str:
    if not _USER_RE.match(user or "") or user == "root":
        raise PfRuleError(f"service account {user!r} is not a valid non-root user name")
    return user


def _network(entry: AllowEntry) -> str:
    net = ipaddress.ip_network(entry.network, strict=False)
    if not (net.is_private or net.is_loopback or net.is_link_local):
        raise PfRuleError(f"public range {net} refused")
    return str(net.network_address) if net.num_addresses == 1 else str(net)


def render_anchor(user: str, allow: Iterable[AllowEntry]) -> str:
    """The anchor body for ``user``. The last rule blocks everything else."""
    user = _check_user(user)
    lines = [
        HEADER,
        f"# Outbound TCP and UDP from user {user}: loopback and the allow list only.",
        "pass out quick on lo0 all",
    ]
    seen: set[tuple[str, Optional[int]]] = set()
    for entry in allow:
        addr = _network(entry)
        port = entry.port
        if port is not None and not (0 < port < 65536):
            raise PfRuleError(f"bad port {port} for {addr}")
        if (addr, port) in seen:
            continue
        seen.add((addr, port))
        note = f"# {entry.origin}" + (f": {entry.role} host" if entry.role else "")
        lines.append(note)
        if port is None:
            lines.append(
                f"pass out quick proto {{ tcp udp }} from any to {addr} "
                f"user {user} keep state"
            )
        else:
            lines.append(
                f"pass out quick proto tcp from any to {addr} port {port} "
                f"user {user} keep state"
            )
    lines.append(
        f"block return out log quick proto {{ tcp udp }} from any to any user {user}"
    )
    return "\n".join(lines) + "\n"


def validate_anchor(text: str, user: str) -> list[str]:
    """Static check of an anchor body. Returns the problems found (none = ok).

    Every rule must be one of the three shapes :func:`render_anchor` writes,
    scoped to ``user``, to a private address, and the block rule must be
    last. This catches hand edits and template drift without ``pfctl``.
    """
    problems: list[str] = []
    try:
        _check_user(user)
    except PfRuleError as exc:
        return [str(exc)]
    rules = [
        ln.strip()
        for ln in text.splitlines()
        if ln.strip() and not ln.lstrip().startswith("#")
    ]
    if not rules:
        return ["anchor has no rules"]
    for n, rule in enumerate(rules, 1):
        match = next((m for r in _RULE_RES if (m := r.match(rule))), None)
        if match is None:
            problems.append(f"rule {n} is not a recognised shape: {rule!r}")
            continue
        groups = match.groupdict()
        if "user" in groups and groups["user"] != user:
            problems.append(f"rule {n} is scoped to {groups['user']!r}, not {user!r}")
        if groups.get("addr"):
            try:
                net = ipaddress.ip_network(groups["addr"], strict=False)
            except ValueError:
                problems.append(f"rule {n} has a bad address {groups['addr']!r}")
            else:
                if not (net.is_private or net.is_loopback or net.is_link_local):
                    problems.append(f"rule {n} passes public range {net}")
        if groups.get("port") and not (0 < int(groups["port"]) < 65536):
            problems.append(f"rule {n} has a bad port")
    if not rules[-1].startswith("block return out"):
        problems.append("the last rule must block all other outbound traffic")
    if sum(1 for r in rules if r.startswith("block")) != 1:
        problems.append("expected exactly one block rule")
    return problems


def pf_conf_lines(anchor_path: str = ANCHOR_PATH) -> tuple[str, str]:
    """The two lines ``/etc/pf.conf`` needs to load the anchor."""
    return (f'anchor "{ANCHOR}"', f'load anchor "{ANCHOR}" from "{anchor_path}"')


def missing_pf_conf_lines(
    pf_conf_text: str, anchor_path: str = ANCHOR_PATH
) -> list[str]:
    """Which of :func:`pf_conf_lines` are not yet in ``pf_conf_text``."""
    have = {ln.strip() for ln in pf_conf_text.splitlines()}
    return [ln for ln in pf_conf_lines(anchor_path) if ln not in have]


def plan(user: str, allow: Sequence[AllowEntry]) -> PfPlan:
    """Render and check the anchor. Raises :class:`PfRuleError` on any problem."""
    text = render_anchor(user, allow)
    problems = validate_anchor(text, user)
    if problems:
        raise PfRuleError("; ".join(problems))
    return PfPlan(anchor_text=text, pf_conf_lines=pf_conf_lines())
