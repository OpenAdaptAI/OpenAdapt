"""What a compiled task is called through: an Agent Skill and an MCP tool.

Both call :func:`openadapt_flow.compile_agent.run_compiled` on the task
directory, so every call goes through the admission check, the system-of-record
read-back and the verify-run receipt. Neither copies the bundle: a copy run
outside the task directory would skip the admission and the confirmed checks.

The skill reuses ``emit-skill``'s step descriptions, which never carry a value
from the recording.
"""

from __future__ import annotations

import ast
import keyword
from pathlib import Path
from typing import TYPE_CHECKING

from openadapt_flow.emit.mcp_sdk import server_import
from openadapt_flow.emit.python_names import PythonNames
from openadapt_flow.emit.skill import _recorded_literals, _slugify, _step_line
from openadapt_flow.ir import Workflow

if TYPE_CHECKING:  # pragma: no cover
    from openadapt_flow.compile_agent.pipeline import FirstRunCompiler

__all__ = ["emit_mcp", "emit_skill_for"]

_SERVER = '''\
"""MCP server exposing one fixed compiled task as one tool.

Generated by openadapt-flow compile-agent. Requires: mcp, openadapt-flow.
Every call runs the fixed admitted task: no model calls, each save read back
from the system of record, and a verify-run receipt.
"""

from __future__ import annotations

from typing import Annotated as {annotated_type}
from pydantic import Field as {field_type}

{sdk_import}
from openadapt_flow.request_binding import mcp_request_scope as {scoped_server_type}

{task_symbol} = {task_dir!r}

{server_symbol} = {server_type}({name!r})


@{server_symbol}.tool(name={tool_name!r})
def {func}({signature}) -> dict:
    """{doc}

    Returns:
        ``verified`` is true only when the program ended VERIFIED and the
        verify-run receipt for the confirmed record checks is VERIFIED.
        ``model_calls`` is 0 on a healthy run. Any other status means the run
        stopped; it is in the exception inbox, and the record should be checked
        before calling again.
    """
    from openadapt_flow.compile_agent import run_compiled_params as {dispatch_symbol}

    if {generation_symbol} == 1:
        with {scoped_server_type}({server_symbol}.get_context()):
            return {dispatch_symbol}({task_symbol}, {values}).to_dict()
    return {dispatch_symbol}({task_symbol}, {values}).to_dict()


async def {bound_call_symbol}(self, name, arguments, context=None):
    with {scoped_server_type}(context):
        return await {server_type}.call_tool(self, name, arguments, context)


if {generation_symbol} == 2:
    from types import MethodType as {method_type_symbol}

    {server_symbol}.call_tool = {method_type_symbol}({bound_call_symbol}, {server_symbol})

if __name__ == "__main__":
    {server_symbol}.run()
'''


def _func_name(task_id: str) -> str:
    name = "".join(ch if ch.isalnum() else "_" for ch in task_id).strip("_").lower()
    if not name or name[0].isdigit():
        name = f"task_{name}"
    return name


def emit_mcp(compiler: "FirstRunCompiler", out_path: Path) -> Path:
    """Write a FastMCP ``server.py`` with one tool for the task."""

    params = sorted(compiler.task.params)
    bad = [p for p in params if keyword.iskeyword(p)]
    if bad:
        raise ValueError(f"parameter names {bad} are Python keywords")
    symbols = PythonNames(params)
    annotated_type = symbols.allocate("Annotated")
    field_type = symbols.allocate("Field")
    server_type = symbols.allocate("FastMCP")
    import_error = symbols.allocate("mcp_import_error")
    scoped_server_type = symbols.allocate("request_scope_for_context")
    bound_call_symbol = symbols.allocate("call_tool_with_request_context")
    method_type_symbol = symbols.allocate("MethodType")
    generation_symbol = symbols.allocate("mcp_generation")
    parse_context_symbol = symbols.allocate("parse_request_context")
    request_scope_symbol = symbols.allocate("request_scope")
    meta_symbol = symbols.allocate("request_meta")
    task_symbol = symbols.allocate("TASK_DIR")
    server_symbol = symbols.allocate("mcp")
    dispatch_symbol = symbols.allocate("run_compiled_params")
    function_symbol = symbols.allocate(_func_name(compiler.task.task_id))
    # MCP binds arguments through a Pydantic field model. Keep every declared
    # schema key separate from both that model and the Python namespace.
    bindings = {name: symbols.allocate("input_" + name) for name in params}
    instruction = compiler.task.instruction.replace('"""', "'''").replace("\\", " ")
    source = _SERVER.format(
        name=compiler.task.task_id,
        task_dir=str(compiler.dir),
        func=function_symbol,
        tool_name=_func_name(compiler.task.task_id),
        annotated_type=annotated_type,
        field_type=field_type,
        server_type=server_type,
        sdk_import=server_import(server_type, import_error, generation_symbol),
        scoped_server_type=scoped_server_type,
        bound_call_symbol=bound_call_symbol,
        method_type_symbol=method_type_symbol,
        generation_symbol=generation_symbol,
        task_symbol=task_symbol,
        server_symbol=server_symbol,
        dispatch_symbol=dispatch_symbol,
        signature=", ".join(
            f"{binding}: {annotated_type}[str, {field_type}(validation_alias={name!r})]"
            for name, binding in bindings.items()
        ),
        parse_context_symbol=parse_context_symbol,
        request_scope_symbol=request_scope_symbol,
        meta_symbol=meta_symbol,
        doc=" ".join(instruction.split()),
        values="{"
        + ", ".join(f"{name!r}: {binding}" for name, binding in bindings.items())
        + "}",
    )
    ast.parse(source)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(source, encoding="utf-8")
    return out_path


def emit_skill_for(bundle_dir: Path, out_dir: Path, cli_line: str) -> Path:
    """Write ``<out_dir>/<slug>/SKILL.md`` for an admitted compiled task."""

    workflow = Workflow.load(bundle_dir)
    slug = _slugify(workflow.name)
    skill_dir = Path(out_dir) / slug
    skill_dir.mkdir(parents=True, exist_ok=True)
    literals = _recorded_literals(workflow)
    params = list(workflow.params)
    lines: list[str] = [
        "---",
        f"name: {slug}",
        (
            f"description: Run the admitted '{workflow.name}' program "
            f"({len(workflow.steps)} steps, no model calls) and confirm the "
            "save in the system of record."
        ),
        "---",
        "",
        f"# {workflow.name}",
        "",
        "A computer-use agent did this task once. Its verified run was compiled "
        "into this program and admitted. Running it makes no model calls.",
        "",
        "## What it does",
        "",
    ]
    lines += [f"1. {_step_line(step, literals)}" for step in workflow.steps]
    lines += ["", "## Parameters", ""]
    if params:
        lines += ["| Name | Type | Required |", "| --- | --- | --- |"]
        lines += [f"| `{name}` | string | yes |" for name in params]
    else:
        lines.append("_This task takes no parameters._")
    lines += [
        "",
        "## Usage",
        "",
        "```bash",
        cli_line,
        "```",
        "",
        "Replace each `<name>` with the value for this request; never reuse a "
        "value from an earlier run. The command exits 0 only when the run ended "
        "VERIFIED: the save was read back from the system of record and the "
        "verify-run receipt for the confirmed checks is VERIFIED. Any other "
        "result stops the run and puts it in the exception inbox; check the "
        "record before you try again. Don't fall back to doing the task by hand "
        "or with a computer-use agent.",
        "",
    ]
    (skill_dir / "SKILL.md").write_text("\n".join(lines), encoding="utf-8")
    return skill_dir
